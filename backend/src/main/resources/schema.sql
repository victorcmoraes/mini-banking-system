create table accounts (
    id bigint primary key,
    owner_name varchar(120) not null,
    balance numeric(19, 2) not null,
    version bigint not null default 0,
    constraint ck_accounts_balance_non_negative check (balance >= 0)
);

create table bank_transactions (
    id bigint generated by default as identity primary key,
    source_account_id bigint not null,
    target_account_id bigint not null,
    amount numeric(19, 2) not null,
    idempotency_key varchar(120) not null,
    status varchar(30) not null,
    failure_reason varchar(255),
    created_at timestamp with time zone not null,
    constraint uk_bank_transactions_idempotency unique (idempotency_key),
    constraint fk_bank_transactions_source foreign key (source_account_id) references accounts(id),
    constraint fk_bank_transactions_target foreign key (target_account_id) references accounts(id),
    constraint ck_bank_transactions_amount_positive check (amount > 0)
);

create index idx_bank_transactions_source on bank_transactions(source_account_id);
create index idx_bank_transactions_target on bank_transactions(target_account_id);
create index idx_bank_transactions_created_at on bank_transactions(created_at);
